"""Training-readiness report: combines `datahub validate` results with the base-model license facts.

python -m datahub.readiness   → reports/training_readiness.md + .json
Each model gets exactly one status. When several blockers apply, the label is the first in this order (the one that
must be resolved first): BASE MODEL → LICENSE → DATA → HUMAN REVIEW → OTHER. All blockers are listed.
"""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MODELS = ["nick-4.8", "hike-6.5", "sona-9.0", "fab-100x", "fab-500x"]
ORDER = ["BASE MODEL", "LICENSE", "DATA", "HUMAN REVIEW", "OTHER"]

# Verified on the Hugging Face Hub (cardData.license + LICENSE file), 2026-11-14.
BASE_LICENSES = {
    "Qwen/Qwen2.5-3B-Instruct": ("qwen-research", False, "Qwen RESEARCH LICENSE AGREEMENT: 'Non-Commercial … research or evaluation purposes only'"),
    "Qwen/Qwen2.5-7B-Instruct": ("apache-2.0", True, "Apache License 2.0"),
    "Qwen/Qwen2.5-14B-Instruct": ("apache-2.0", True, "Apache License 2.0"),
    "Qwen/Qwen2.5-Coder-32B-Instruct": ("apache-2.0", True, "Apache License 2.0"),
}
HUB_HEAD = {"Qwen/Qwen2.5-7B-Instruct": "a09a35458c702b33eeacc393d103063234e8bc28",
            "Qwen/Qwen2.5-14B-Instruct": "cf98f3b3bbb457ad9e2bb7baf9a0125b6b88caa8",
            "Qwen/Qwen2.5-Coder-32B-Instruct": "381fc969f78efac66bc87ff7ddeadb7e73c218a7"}


def main() -> dict:
    val = json.loads((ROOT / "reports" / "validation_report.json").read_text())
    out = {}
    for m in MODELS:
        checks = {c["check"]: c for c in val["models"].get(m, [])}
        prof = json.loads((ROOT / "datasets" / m / "profile.json").read_text())
        base, rev = prof.get("base_model"), prof.get("base_model_revision")
        blockers = []
        if not base:
            blockers.append(("BASE MODEL", "No base model configured. Choose one (options in reports/base_model_options.md) — needs your approval."))
        else:
            lic = BASE_LICENSES.get(base)
            if lic and not lic[1]:
                blockers.append(("LICENSE", f"{base} is under {lic[0]} ({lic[2]}): no commercial use. Keep the config unchanged until you approve an "
                                            "alternative (reports/base_model_options.md)."))
            if not rev:
                blockers.append(("OTHER", f"{base} revision not pinned (resolved and recorded at training time; current Hub head "
                                          f"{HUB_HEAD.get(base, '?')[:12]}). Pin it for a reproducible run."))
        for name in ("record_target", "domain_minimums", "language_minimums"):
            c = checks.get(name)
            if c and c["status"] != "PASS":
                blockers.append(("DATA", f"{name}: {c['detail'] if isinstance(c['detail'], str) else json.dumps(c['detail'], ensure_ascii=False)}"))
        c = checks.get("human_review_minimum")
        if c and c["status"] != "PASS":
            blockers.append(("HUMAN REVIEW", c["detail"]))
        for name, c in checks.items():
            if c["status"] == "FAIL":
                blockers.append(("OTHER", f"validation FAIL: {name}: {c['detail']}"))
        status = "READY FOR TRAINING" if not blockers else f"BLOCKED — {min((b[0] for b in blockers), key=ORDER.index)}"
        out[m] = {"status": status, "blockers": blockers, "base_model": base, "base_model_revision": rev}
    (ROOT / "reports" / "training_readiness.json").write_text(json.dumps(out, indent=1, ensure_ascii=False))
    L = ["# Training readiness", "", "Generated by `python -m datahub.readiness` from reports/validation_report.json and the verified base-model licenses.",
         "Training must not start for any model that is not READY FOR TRAINING.", "", "| Model | Status | Base model |", "|---|---|---|"]
    L += [f"| {m} | **{o['status']}** | {o['base_model'] or '—'} |" for m, o in out.items()]
    for m, o in out.items():
        L += ["", f"## {m}", ""] + ([f"- **{k}** — {d}" for k, d in o["blockers"]] or ["- no blockers"])
    (ROOT / "reports" / "training_readiness.md").write_text("\n".join(L) + "\n")
    for m, o in out.items():
        print(f"{m:10s} {o['status']}")
    return out


if __name__ == "__main__":
    main()
